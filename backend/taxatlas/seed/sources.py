# Discovered / programmatic registries live in their own modules so several maintainers can extend the
# registry without touching this file. Each module exports `SOURCES: list[dict]` in the same shape.
from importlib import import_module as _import_module  # noqa: E402

for _mod in (
    "sources_discovered_emea",
    "sources_discovered_apac",
    "sources_discovered_americas",
    "sources_rates_watch",
):
    try:
        SOURCES.extend(_import_module(f"taxatlas.seed.{_mod}").SOURCES)
    except ImportError:
        pass


def by_slug(slug: str) -> dict | None:
    return next((s for s in SOURCES if s["slug"] == slug), None)


__all__ = ["SOURCES", "by_slug"]
