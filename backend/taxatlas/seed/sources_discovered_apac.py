"""Discovered sources — Asia-Pacific (2026-08-25 discovery pass).

Same shape as ``app.seed.sources.SOURCES``; merged into the registry by the extension hook at the bottom of
``sources.py``. Every URL below was probed on 2026-08-25 with the TaxAtlas user agent and trialled twice
against a scratch database (``DATABASE_URL=sqlite:////tmp/apac.db``); a source had to return HTTP 200 and keep
>= 3 relevant items to be enabled.

Conventions
- ``authority`` is the local-language name; ``authority_en`` the English rendering when they differ.
- **Backstop** rows are keyword searches over aggregated press (``adapter="news"``, ``url="news://<slug>"``; the
  adapter tries GDELT, then Bing News, then Google News — Google answers 503 from GCP egress, see docs/sources.md
  "Backstops") in the local language when the official site is bot-blocked, JS-only or unreachable from outside the
  country. They are ``category="news"`` with ``tax_filter`` on and ``include_keywords`` so only tax/customs items
  survive, and their note carries the official URL that was found so the row can be repointed once a browser adapter
  or a working listing exists.
- Blocked officials are kept as ``adapter="html", enabled=False`` with a ``note`` (``needs browser adapter`` when a
  headless browser would fix it) so the gap is visible in the admin UI and ``check-urls`` can re-probe them.
- Sub-national rows use ISO 3166-2 codes that exist in ``jurisdictions.py`` (IN-MH, CN-SH, JP-13, AU-QLD ...).

Schedule policy (as in sources.py): courts daily, regulators every 6h, tariff/trade every 4h, news every 6h or
4x daily; minutes are staggered so the scheduler never fires every job at once.
"""

