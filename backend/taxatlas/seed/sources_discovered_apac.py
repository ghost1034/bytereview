def _backstop(
    slug: str,
    name: str,
    jurisdiction: str,
    query: str,
    hl: str,
    gl: str,
    include: list[str],
    official: str,
    reason: str,
    cron: str,
    tax_types: list[T] | None = None,
    authority: str = "Google News (aggregated press)",
    lang: str | None = None,  # kept for call-site compatibility; the news adapter derives Google's ceid from `hl`
) -> dict:
    """Keyword-search backstop over aggregated press (adapter="news": GDELT -> Bing -> Google News, see adapters/news.py).

    `gl` was the Google News edition; when it differs from the jurisdiction's country it is kept as `google_country`
    so the Google provider keeps the edition that answered on 2026-08-25 while GDELT/Bing search the jurisdiction itself.
    """
    country = jurisdiction.split("-")[0]
    cfg: dict = {"query": query, "lang": hl, "country": country}
    if gl and gl != country:
        cfg["google_country"] = gl
    cfg.update(
        {
            "tax_filter": True,
            "include_keywords": include,
            "max_items": 40,
            "note": f"backstop: Google News ({hl}). Official site {official} — {reason}",
        }
    )
    return {
        "slug": slug,
        "name": name,
        "url": f"news://{slug}",
        "jurisdiction_code": jurisdiction,
        "tax_types": tax_types or _CORE,
        "category": "news",
        "adapter": "news",
        "config": cfg,
        "schedule_cron": cron,
        "enabled": True,
        "authority": authority,
    }


def _blocked(
    slug: str,
    name: str,
    url: str,
    jurisdiction: str,
    category: str,
    note: str,
    cron: str,
    authority: str,
    tax_types: list[T] | None = None,
    authority_en: str | None = None,
    court: str | None = None,
) -> dict:
    cfg: dict = {"item_selector": "article", "note": note}
    if court:
        cfg["court"] = court
    row = {
        "slug": slug,
        "name": name,
        "url": url,
        "jurisdiction_code": jurisdiction,
        "tax_types": tax_types or _CORE,
        "category": category,
        "adapter": "html",
        "config": cfg,
        "schedule_cron": cron,
        "enabled": False,
        "authority": authority,
    }
    if authority_en:
        row["authority_en"] = authority_en
    return row


