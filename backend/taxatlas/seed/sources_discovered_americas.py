"""Discovered sources — Americas (Central America, Caribbean, South America, courts, trade, sub-national).

Same shape as app.seed.sources.SOURCES. Every URL was probed on 2026-08-25 with the TaxAtlas user agent and trialled
twice against a scratch database (`python -m app.crawler run --source <slug> --force-network`); a source had to return
200 and keep >= 3 relevant items to be enabled. Where the official site exposes no parseable listing (client-rendered
portals, SharePoint without feeds, TLS-chain failures, timeouts) the row is kept disabled with a ``config["note"]`` and
a Google News RSS backstop (``…-news-backstop``) is registered next to it — the note names the official URL so the
backstop can be retired when the site becomes reachable.

Schedule policy mirrors sources.py: courts daily, regulators/news 4x daily, tariff/trade every 4h; minutes staggered.
"""

