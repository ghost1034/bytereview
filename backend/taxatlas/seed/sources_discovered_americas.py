def _backstop(
    slug: str,
    code: str,
    country: str,
    query: str,
    hl: str,
    official: str,
    tax_types: list,
    minute: int,
    authority: str,
    authority_en: str | None = None,
    category: str = "news",
    extra_config: dict | None = None,
) -> dict:
    """Keyword-search backstop over aggregated press (adapter="news": GDELT -> Bing -> Google News, adapters/news.py)."""
    cfg = {
        "query": query,
        "lang": hl,
        "country": code.split("-")[0],
        "note": f"backstop: Google News ({hl}). Official site: {official}",
        "max_items": 40,
    }
    cfg.update(extra_config or {})
    spec = {
        "slug": slug,
        "name": f"{country} — tax news (Google News backstop)",
        "url": f"news://{slug}",
        "jurisdiction_code": code,
        "tax_types": tax_types,
        "category": category,
        "adapter": "news",
        "config": cfg,
        "schedule_cron": f"{minute} 3,9,15,21 * * *",
        "enabled": True,
        "authority": authority,
    }
    if authority_en:
        spec["authority_en"] = authority_en
    return spec


